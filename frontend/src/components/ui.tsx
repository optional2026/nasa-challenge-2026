// Shared UI primitives.
import { useEffect, useState } from "react";
import { LuCircleAlert, LuLoaderCircle, LuX } from "react-icons/lu";
import { SEVERITY_LABEL, SEVERITY_TONE, STATUS_INFO, Tone, humanize } from "../lib/format";

export function Panel({ title, actions, children, className = "", tone, id }:
  { title?: any; actions?: any; children: any; className?: string; tone?: Tone; id?: string }) {
  return (
    <section className={`panel ${tone ? "tone-" + tone : ""} ${className}`} id={id}>
      {(title || actions) && (
        <header className="panel-head">
          {title && <h2>{title}</h2>}
          {actions && <div className="panel-actions">{actions}</div>}
        </header>
      )}
      <div className="panel-body">{children}</div>
    </section>
  );
}

export function Severity({ value }: { value: string }) {
  return <span className={`sev sev-${SEVERITY_TONE[value] || "none"}`}>{SEVERITY_LABEL[value] || humanize(value)}</span>;
}

export function StatusPill({ status }: { status: string }) {
  const info = STATUS_INFO[status] || { tone: "none", label: humanize(status) };
  return <span className={`sev sev-${info.tone}`}>{info.label}</span>;
}

export function Chip({ children, tone = "plain", title }: { children: any; tone?: string; title?: string }) {
  return <span className={`chip chip-${tone}`} title={title}>{children}</span>;
}

export function Synthetic({ show = true }: { show?: boolean }) {
  return show ? <span className="synthetic" title="Generated by the ASTRA simulator or demo seed — not real crew data">SYNTHETIC</span> : null;
}

export function Loading({ label = "Loading" }: { label?: string }) {
  return <div className="loading"><LuLoaderCircle className="spin" aria-hidden /> {label}…</div>;
}

export function ErrorBox({ error, onRetry }: { error: any; onRetry?: () => void }) {
  if (!error) return null;
  return (
    <div className="error-box" role="alert">
      <LuCircleAlert aria-hidden />
      <div>
        <strong>{error.message || String(error)}</strong>
        {error.details && Array.isArray(error.details) && (
          <ul>{error.details.slice(0, 6).map((d: any, i: number) => <li key={i}>{d.msg || (d.errors ? d.errors.join("; ") : JSON.stringify(d))}</li>)}</ul>
        )}
        {onRetry && <button className="btn btn-quiet" onClick={onRetry}>Try again</button>}
      </div>
    </div>
  );
}

export function Empty({ children }: { children: any }) {
  return <div className="empty">{children}</div>;
}

export function KV({ items }: { items: [string, any][] }) {
  return (
    <dl className="kv">
      {items.filter(([, v]) => v !== undefined).map(([k, v]) => (
        <div key={k}><dt>{k}</dt><dd>{v ?? "—"}</dd></div>
      ))}
    </dl>
  );
}

export function Tabs({ tabs, value, onChange }: { tabs: [string, string][]; value: string; onChange: (v: string) => void }) {
  return (
    <div className="tabs" role="tablist">
      {tabs.map(([k, label]) => (
        <button key={k} role="tab" aria-selected={value === k} className={value === k ? "active" : ""} onClick={() => onChange(k)}>{label}</button>
      ))}
    </div>
  );
}

export function Drawer({ open, onClose, title, children }: { open: boolean; onClose: () => void; title: any; children: any }) {
  useEffect(() => {
    if (!open) return;
    const k = (e: KeyboardEvent) => { if (e.key === "Escape") onClose(); };
    window.addEventListener("keydown", k);
    return () => window.removeEventListener("keydown", k);
  }, [open, onClose]);
  if (!open) return null;
  return (
    <div className="drawer-backdrop" onClick={onClose}>
      <aside className="drawer" role="dialog" aria-modal="true" aria-label={typeof title === "string" ? title : "Details"} onClick={(e) => e.stopPropagation()}>
        <header><h2>{title}</h2><button className="icon-btn" onClick={onClose} aria-label="Close"><LuX /></button></header>
        <div className="drawer-body">{children}</div>
      </aside>
    </div>
  );
}

export function useAsyncAction() {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<any>(null);
  const run = async (fn: () => Promise<any>) => {
    setBusy(true); setError(null);
    try { return await fn(); } catch (e) { setError(e); return undefined; } finally { setBusy(false); }
  };
  return { busy, error, run, setError };
}

export function Field({ label, hint, children, wide }: { label: string; hint?: string; children: any; wide?: boolean }) {
  return (
    <label className={`field ${wide ? "wide" : ""}`}>
      <span className="field-label">{label}</span>
      {children}
      {hint && <span className="field-hint">{hint}</span>}
    </label>
  );
}

export function Scale({ labels, value, onChange, name, allowSkip = true }:
  { labels: string[]; value: number | null; onChange: (v: number | null) => void; name: string; allowSkip?: boolean }) {
  return (
    <div className="scale" role="radiogroup" aria-label={name}>
      {labels.map((l, i) => (
        <button type="button" key={l} role="radio" aria-checked={value === i + 1} className={value === i + 1 ? "on" : ""}
          onClick={() => onChange(i + 1)}>{l}</button>
      ))}
      {allowSkip && <button type="button" className={`skip ${value === null ? "on" : ""}`} onClick={() => onChange(null)}>Skip</button>}
    </div>
  );
}
